// กฎแยกเคสที่ใกล้กัน
const DISAMBIGUATION = `กฎแยกเคสที่ใกล้กัน:
- "วันนี้ว่างไหม" / "พรุ่งนี้ว่างไหม" = ถามคิวว่างเพื่อนัด จัดเป็น booking ส่วน "วันนี้เปิดไหม" จัดเป็น faq
- เลื่อน/เปลี่ยน + พูดถึงนัดเดิม จัดเป็น reschedule ถามคิวว่างเฉยๆ จัดเป็น booking
- "นัดตรวจ" จัดเป็น booking และ slots.service = "ตรวจฟัน" ส่วน "นัดปรึกษา [เรื่อง]" จัดเป็น booking และ slots.service = "ปรึกษา[เรื่อง]"
- "สนใจ [บริการ]" อย่างเดียว จัดเป็น faq (ตอบข้อมูลบริการ + ชวนพิมพ์ "จองคิว") ถ้ามีคำว่า นัด จอง คิว ว่าง จัดเป็น booking
- ตัวเลข วันเวลา หรือตัวเลือกโดดๆ ที่ไม่มีกริยา จัดเป็น slot_reply (ไม่ใช่ booking)
- ทักทายแล้วมีเรื่องอื่นในข้อความเดียว จัดตามเรื่องนั้น ไม่ใช่ greeting
- อาการ + ขอนัด จัดเป็น booking ถ้าเป็นอาการรุนแรง + ขอนัด จัดเป็น emergency
- "รับรีเทนเนอร์" จัดเป็น request หรือ booking (บริการที่ไม่ต้องใช้คุณหมอ) ส่วน "รีเทนเนอร์บีบเหงือก" "เจียรีเทนเนอร์" จัดเป็น symptom (ต้องใช้คุณหมอ)
- คิว สปสช. เป็นโควต้ารายสัปดาห์ ห้ามตอบเรื่องคิวว่างหรือโควต้าเอง
- ถ้ามีชื่อ/เบอร์ของผู้ป่วยมากกว่า 1 คนในข้อความเดียว ให้ multiple_patients = true
- slots ใส่คำที่ลูกค้าพิมพ์ตามจริง (date_text, time_text) ห้ามคำนวณหรือแปลงวันที่เอง`;

export function buildIntentGuide(): string {
  const lines = INTENT_NAMES.map((name) => {
    const { description, examples } = INTENTS[name];
    return `- ${name}: ${description}\n  ตัวอย่าง: ${examples.join(" | ")}`;
  });
  return `${lines.join("\n")}\n\n${DISAMBIGUATION}`;
}

